/**
 * Tells whether the attributes of the icon are a list of settings.
 *
 * @since TBD
 */
final class Kadence_Blocks_Single_Icon_Array_Condition implements Kadence_Blocks_Css_Input_Condition {

	/**
	 * Whether the attributes are a list.
	 *
	 * @since TBD
	 *
	 * @param Kadence_Blocks_Css_Build_Input $input What the section needs to write its CSS.
	 *
	 * @return bool
	 */
	public function is_met( Kadence_Blocks_Css_Build_Input $input ): bool {
		return is_array( $input->attributes() );
	}
}
