<?php
/**
 * Writes the class map the CSS builder autoloader reads.
 *
 * Usage: php bin/generate-css-classmap.php <includes directory> <output file> <folder in includes>...
 *
 * Every class, abstract class and interface declared in the folders is listed with its path relative to the includes
 * directory. Run it after adding, moving or removing a class; a test fails when the map is stale.
 *
 * @package Kadence Blocks
 */

if ( 'cli' !== PHP_SAPI ) {
	exit( 1 );
}

/**
 * Write the class map.
 *
 * @param string[] $argv The command line arguments.
 *
 * @return void
 */
function kadence_blocks_generate_css_classmap( array $argv ): void {
	[ , $includes, $output ] = $argv + [ null, null, null ];
	$folders                 = array_slice( $argv, 3 );

	if ( ! $includes || ! $output || ! $folders ) {
		fwrite( STDERR, "Usage: php bin/generate-css-classmap.php <includes directory> <output file> <folder>...\n" );
		exit( 1 );
	}

	$includes = rtrim( realpath( $includes ), '/' ) . '/';
	$map      = [];

	foreach ( $folders as $folder ) {
		$files = new RecursiveIteratorIterator( new RecursiveDirectoryIterator( $includes . $folder, FilesystemIterator::SKIP_DOTS ) );

		foreach ( $files as $file ) {
			if ( 'php' !== $file->getExtension() || 'classmap.php' === $file->getFilename() ) {
				continue;
			}

			preg_match_all( '/^(?:final |abstract )?(?:class|interface|trait) ([A-Za-z0-9_]+)/m', (string) file_get_contents( $file->getPathname() ), $found );

			foreach ( $found[1] as $class_name ) {
				$map[ $class_name ] = substr( $file->getPathname(), strlen( $includes ) );
			}
		}
	}

	ksort( $map );

	$lines = [ "<?php\n// Generated by bin/generate-css-classmap.php. Do not edit.\n\nreturn [" ];

	foreach ( $map as $class_name => $path ) {
		$lines[] = "\t'" . $class_name . "' => '" . $path . "',";
	}

	$lines[] = "];\n";

	file_put_contents( $output, implode( "\n", $lines ) );

	echo count( $map ) . " classes mapped.\n";
}

kadence_blocks_generate_css_classmap( $argv );
